//! Band 11 private native addresses (ported from the former
//! `scripts/generate_band11_native_config.py`).

use crate::error::{Error, Result};
use crate::model::TargetPack;
use serde_json::Value;
use std::collections::BTreeMap;
use std::path::Path;

pub struct NativeConfig {
    /// Raw `loader/native-bindings.json`.
    pub profile: Value,
    /// Macro name -> callable (Thumb) address for functions, entry for globals.
    pub addresses: BTreeMap<String, u64>,
}

fn hex(value: &Value, what: &str) -> Result<u64> {
    let s = value
        .as_str()
        .ok_or_else(|| Error::other(format!("missing {what}")))?;
    u64::from_str_radix(s.trim_start_matches("0x"), 16)
        .map_err(|_| Error::other(format!("bad {what}: {s}")))
}

pub fn load(root: &Path, pack: &TargetPack) -> Result<NativeConfig> {
    let profile: Value =
        serde_json::from_str(&std::fs::read_to_string(root.join("loader/native-bindings.json"))?)?;
    if profile["schema"] != 1
        || profile["target_id"] != pack.target_id.as_str()
        || profile["firmware_sha256"] != pack.firmware_sha256.as_str()
    {
        return Err(Error::other("native profile identity differs from target pack"));
    }
    let mut symbols: BTreeMap<String, Value> = BTreeMap::new();
    for entry in std::fs::read_dir(root.join("symbols"))? {
        let path = entry?.path();
        if path.extension().and_then(|e| e.to_str()) != Some("json") {
            continue;
        }
        let record: Value = serde_json::from_str(&std::fs::read_to_string(&path)?)?;
        let name = record["name"].as_str().unwrap_or_default().to_string();
        if symbols.insert(name.clone(), record).is_some() {
            return Err(Error::other(format!("duplicate symbol name: {name}")));
        }
    }
    let mut addresses = BTreeMap::new();
    let bindings = profile["bindings"]
        .as_object()
        .ok_or_else(|| Error::other("native profile has no bindings"))?;
    for (macro_name, name) in bindings {
        let valid = macro_name.starts_with(|c: char| c.is_ascii_uppercase())
            && macro_name.len() >= 2
            && macro_name
                .chars()
                .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_');
        if !valid {
            return Err(Error::other(format!("invalid macro: {macro_name}")));
        }
        let name = name.as_str().unwrap_or_default();
        let record = symbols
            .get(name)
            .ok_or_else(|| Error::other(format!("unknown symbol: {name}")))?;
        if record["target_id"] != pack.target_id.as_str()
            || record["provenance"]["firmware_sha256"] != pack.firmware_sha256.as_str()
        {
            return Err(Error::other(format!("wrong firmware provenance: {name}")));
        }
        let policy = record["policy"].as_str().unwrap_or_default();
        let reviewed = matches!(
            record["status"].as_str(),
            Some("STATIC_RECOVERED" | "DEVICE_PROBED" | "DEVICE_PROVEN")
        );
        if !reviewed || !matches!(policy, "restricted" | "managed") {
            return Err(Error::other(format!(
                "native test ABI requires reviewed static evidence: {name}"
            )));
        }
        for evidence in record["proof"]["evidence_ids"].as_array().into_iter().flatten() {
            let id = evidence.as_str().unwrap_or_default();
            if !root.join("evidence").join(format!("{id}.json")).is_file() {
                return Err(Error::other(format!("missing native evidence: {id}")));
            }
        }
        let entry = hex(&record["entry_address"], "entry_address")?;
        let value = if record["kind"] == "function" {
            let callable = hex(&record["callable_address"], "callable_address")?;
            if entry & 1 != 0 || callable != entry | 1 {
                return Err(Error::other(format!("invalid Thumb callable: {name}")));
            }
            callable
        } else {
            entry
        };
        addresses.insert(macro_name.clone(), value);
    }
    Ok(NativeConfig { profile, addresses })
}

pub fn render(pack: &TargetPack, config: &NativeConfig) -> String {
    let mut out = format!(
        "/* Generated by `canopus target generate`. Static private ABI; device pending.\n * {}\n * SHA256 {} */\n#ifndef CANOPUS_BAND11_ADDRESSES_H\n#define CANOPUS_BAND11_ADDRESSES_H\n",
        pack.target_id, pack.firmware_sha256
    );
    for (name, value) in &config.addresses {
        out.push_str(&format!("#define {name} 0x{value:08X}u\n"));
    }
    out.push_str("#endif\n");
    out
}
